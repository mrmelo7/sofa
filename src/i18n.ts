export type Lang = keyof typeof dicts;
export const LANGS: Record<Lang, string> = {
  en: "English",
  "pt-BR": "Português (Brasil)",
  es: "Español",
};

const LANG_KEY = "lang";
const langs = Object.keys(dicts) as Lang[];

/** Saved choice, else the first OS language that matches exactly or by base ("pt-PT" → "pt-BR"). */
export function initialLang(): Lang {
  const saved = localStorage.getItem(LANG_KEY);
  if (langs.includes(saved as Lang)) return saved as Lang;
  for (const l of navigator.languages) {
    const hit =
      langs.find((x) => x === l) ??
      langs.find((x) => x.split("-")[0] === l.split("-")[0]);
    if (hit) return hit;
  }
  return "en";
}

export function saveLang(l: Lang) {
  localStorage.setItem(LANG_KEY, l);
  document.documentElement.lang = l;
  // The Game Bar widget is another origin; the backend hands it the language.
  if (isTauri())
    void invoke("set_language", { lang: l }).catch(() => undefined);
}
export const isLang = (value: unknown): value is Lang =>
  langs.includes(value as Lang);

export const translator =
  (l: Lang) =>
  (key: keyof Dict, vars: Record<string, string> = {}) =>
    dicts[l][key].replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? "");

export type Translate = ReturnType<typeof translator>;
